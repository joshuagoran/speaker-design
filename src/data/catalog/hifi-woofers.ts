// Hi-fi woofers. src/lib/data.ts adds the comparable Xmax (HIFI_WOOFERS keeps this order).
// To add an entry, append an object literal to the table. The type annotation makes the compiler check it exactly:
// a misspelt, extra or missing field, a string where a number belongs or a value outside its union (maker id, size
// class, tweeter type) is an error.
// Prices are US dollars from US vendors only; `src` names the vendor and the month the price was read.
// Never drop a part because a spec is missing: use null where the type allows it and say what is missing in `note`.
// Pure data: no logic, no derived fields (src/lib/data.ts derives and sorts).
// Fields: id, name, maker (a MAKER_NAMES id), size in, lb, price $, src, fmax (highest usable frequency, Hz, null if
// unpublished), note.
// ts (the maker's Thiele-Small figures): Fs Hz, Vas L, Sd cm², Re Ω, Bl T·m, Mms g, aes W (AES rating), disp L
// (null where unpublished), Hvc / Hg (coil and gap heights) mm, and `pub` = every excursion figure the maker
// publishes, one-way mm, with its formula and source URL. Do not add Xmax / xmax: src/lib/xmax derives them.
// Hi-fi ts also lists Le mH, sens dB (the note says 2.83 V or 1 W) and imp Ω.
// ---- Hi-fi tab: 2-way home speakers (researched Sep 2026) ----
// DIY 2-way hi-fi driver shortlist. Compiled 30 Sep 2026.
// Prices come from US vendors only (parts-express.com, madisoundspeakerstore.com, usspeaker.com).
// Tags in each note say where the specs came from:
//   [maker]  = checked against the manufacturer datasheet or product page
//   [vendor] = vendor page only (usually the maker's numbers copied), not checked against the maker
// Missing specs are null and the note says so. "lb" is net weight where the maker publishes it;
// otherwise it is the vendor's shipping weight, and the note says so.
// Madisound pages showed "out of stock" on every product fetched, which may be a page-template
// artifact; check stock before ordering.
